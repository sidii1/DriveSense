"""Pilot audit on the 57 annotated CCD accident clips (exp3_v2_test run). Writes figures + macros."""
import pandas as pd, numpy as np, json
import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
import sys
# usage: python pilot.py <results dir with frame_features_all.csv + temporal_tests.csv> <paper dir>
B=(sys.argv[1] if len(sys.argv)>1 else 'experiments/exp3_ccd/results_v1_backup/exp3_v2_test').rstrip('/')+'/'
OUT=(sys.argv[2] if len(sys.argv)>2 else '.').rstrip('/')+'/'
fr=pd.read_csv(B+'frame_features_all.csv'); tt=pd.read_csv(B+'temporal_tests.csv').set_index('feature')
rng=np.random.default_rng(0)
plt.rcParams.update({"font.family":"serif","font.size":8,"axes.linewidth":0.6,"pdf.fonttype":42})
def curve(feat):
    d=fr[(fr.t_rel>=-3.0)&(fr.t_rel<0)].copy(); d['bin']=(d.t_rel*10).round()/10
    m=d.groupby(['video_id','bin'])[feat].mean().unstack('bin'); a=m.values
    mu=np.nanmean(a,0); bs=np.array([np.nanmean(a[rng.integers(0,len(a),len(a))],0) for _ in range(1000)])
    return m.columns.values, mu, np.nanpercentile(bs,2.5,0), np.nanpercentile(bs,97.5,0)
fig,axes=plt.subplots(1,2,figsize=(4.8,1.9))
ax=axes[0]
for feat,lab,ls,mk in [('has_det','any detection','-','o'),('has_ttc','in-path TTC available','--','s')]:
    x,mu,lo,hi=curve(feat); ax.plot(x,mu,ls,color='k',lw=1,marker=mk,ms=2,markevery=5,label=lab); ax.fill_between(x,lo,hi,color='0.8',lw=0)
ax.set_xlabel('time to accident onset (s)'); ax.set_ylabel('fraction of frames'); ax.set_ylim(0,1); ax.legend(frameon=False,fontsize=6.5,loc='upper right'); ax.set_title('(a) detector-dependent coverage',fontsize=7.5)
ax=axes[1]; x,mu,lo,hi=curve('flow_mag_center'); ax.plot(x,mu,'-',color='k',lw=1); ax.fill_between(x,lo,hi,color='0.8',lw=0)
ax.set_xlabel('time to accident onset (s)'); ax.set_ylabel('central flow magnitude'); ax.set_title('(b) detector-free motion cue',fontsize=7.5)
for a in axes:
    for s in ('top','right'): a.spines[s].set_visible(False)
    for b in (-2,-1): a.axvline(b,color='0.5',lw=0.4,ls=':')
fig.tight_layout(pad=0.3); fig.savefig(OUT+'figures/fig_pilot_curves.pdf'); 
# macros
g=fr.groupby('video_id').first()
pre=fr[fr.t_rel<0]
w=pd.cut(pre.t_rel,[-3.0001,-2,-1,0],right=False,labels=['early','mid','late'])
alert=(pre.max_inv_ttc_path.fillna(0)>0.5)
ar=alert.groupby(w,observed=False).mean()
M={}
M['PilotN']=fr.video_id.nunique(); M['PilotFrames']=len(fr)
M['PilotDay']=int((g.timing=='Day').sum()); M['PilotNight']=int((g.timing=='Night').sum())
M['PilotNormalW']=int((g.weather=='Normal').sum()); M['PilotSnow']=int((g.weather=='Snowy').sum()); M['PilotRain']=int((g.weather=='Rainy').sum())
M['PilotEgo']=int((g.egoinvolve=='Yes').sum())
M['PilotOnsetMed']=f"{g.t_event.median():.1f}"; M['PilotOnsetMin']=f"{g.t_event.min():.1f}"; M['PilotOnsetMax']=f"{g.t_event.max():.1f}"
M['LaneRate']=f"{100*fr.lane_ok.mean():.1f}"
M['LaneRateRain']=f"{100*fr[fr.weather=='Rainy'].lane_ok.mean():.1f}"
M['LaneRateSnow']=f"{100*fr[fr.weather=='Snowy'].lane_ok.mean():.1f}"
M['LaneRateNormal']=f"{100*fr[fr.weather=='Normal'].lane_ok.mean():.1f}"
M['LaneClipsAny']=f"{100*fr.groupby('video_id').lane_ok.any().mean():.0f}"
M['TTCClipsAny']=int(fr.groupby('video_id').has_ttc.max().sum())
M['AlertEarly']=f"{100*ar['early']:.1f}"; M['AlertMid']=f"{100*ar['mid']:.1f}"; M['AlertLate']=f"{100*ar['late']:.1f}"
for key,f in [('Det','has_det'),('TTC','has_ttc'),('Veh','n_vehicles'),('Flow','flow_mag_center'),('Occ','occupancy'),('InvTTC','max_inv_ttc_path'),('Dist','min_dist_path_m'),('Sharp','sharpness'),('Bright','brightness'),('Glare','glare_frac'),('Dark','dark_channel'),('Contrast','contrast'),('Div','flow_div_center'),('VRU','n_vru')]:
    r=tt.loc[f]; M[f'T{key}N']=int(r.n_videos)
    M[f'T{key}Early']=f"{r.median_early:.3g}"; M[f'T{key}Late']=f"{r.median_late:.3g}"
    M[f'T{key}Diff']=f"{r.median_diff_late_minus_early:+.3g}"; M[f'T{key}Lo']=f"{r.ci95_low:.3g}"; M[f'T{key}Hi']=f"{r.ci95_high:.3g}"
    M[f'T{key}Inc']=f"{100*r.prop_increase:.0f}"; M[f'T{key}Dec']=f"{100*r.prop_decrease:.0f}"
    p=r.wilcoxon_p_holm; M[f'T{key}P']=("$<$0.001" if p<1e-3 else f"{p:.2f}")
json.dump(M,open(OUT+'pilot_macros.json','w'),indent=1)
with open(OUT+'generated_pilot.tex','w',newline='\n') as f:
    f.write('% AUTO-GENERATED by pilot.py from the full CCD accident-clip run. Do not edit by hand.\n')
    for k,v in M.items(): f.write(f'\\newcommand{{\\{k}}}{{{v}}}\n')
print(json.dumps(M,indent=0))

# ---- nicely formatted pilot table body ----
def fp(p): return "$<$0.001" if p<1e-3 else (f"{p:.3f}" if p<0.01 else f"{p:.2f}")
def fn(x):
    if x<0: return "$-$"+fn(-x)
    if x==0: return "0"
    ax=abs(x)
    if ax>=100: return f"{x:.0f}"
    if ax>=10: return f"{x:.1f}"
    if ax>=0.1: return f"{x:.2f}"
    if ax>=0.01: return f"{x:.3f}"
    return f"{x:.1e}".replace("e-0","e$-$").replace("e-","e$-$")
rows=[('Detector-dependent',None),('has_det','Frames with any detection'),('n_vehicles','Vehicles per frame'),('occupancy','Box area fraction'),('has_ttc','Frames with in-path TTC'),('max_inv_ttc_path','Max in-path $1/\\tau$ (s$^{-1}$)$^{\\dagger}$'),('min_dist_path_m','Min in-path distance (m)$^{\\dagger}$'),
      ('Detector-free',None),('flow_mag_center','Central flow magnitude'),('flow_div_center','Central flow divergence'),('sharpness','Sharpness (Laplacian var.)'),('brightness','Brightness'),('contrast','Contrast'),('glare_frac','Glare fraction'),('dark_channel','Dark channel')]
with open(OUT+'generated_pilot_table.tex','w',newline='\n') as f:
    f.write('% AUTO-GENERATED by pilot.py from temporal_tests.csv (full CCD accident set). Do not edit by hand.\n')
    f.write('\\begin{tabular}{@{}lrrrlrr@{}}\n\\toprule\n')
    f.write('Cue & $n$ & Early & Late & Change [95\\% CI] & Inc/Dec & $p_{\\mathrm{Holm}}$\\\\\n\\midrule\n')
    for key,lab in rows:
        if lab is None: f.write(f'\\emph{{{key} cues}} & & & & & &\\\\\n'); continue
        r=tt.loc[key]
        f.write(f"{lab} & {int(r.n_videos)} & {fn(r.median_early)} & {fn(r.median_late)} & {fn(r.median_diff_late_minus_early)} [{fn(r.ci95_low)}, {fn(r.ci95_high)}] & {100*r.prop_increase:.0f}/{100*r.prop_decrease:.0f} & {fp(r.wilcoxon_p_holm)}\\\\\n")
    f.write('\\bottomrule\n\\end{tabular}\n')
print(open(OUT+'generated_pilot_table.tex').read())
