"""STEP 8 (C5b): per-frame runtime of each pipeline stage on this machine (1280x720 CCD frames).
Run on an otherwise idle machine:  python 08_runtime.py <video_dir> <paper_dir> [device]
Writes results/eval/runtime.json and paper/generated_runtime.tex (macros)."""
import json
import sys
import time
from pathlib import Path

import cv2
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import config as C
from perception.detector import Detector
from perception.flow import FlowEstimator
from perception.kinematics import TrackKinematics, frame_summary
from perception.lane import detect_lane
from perception.scene import scene_features

vdir, pdir = Path(sys.argv[1]), Path(sys.argv[2])
dev = sys.argv[3] if len(sys.argv) > 3 else "0"
det, fe = Detector(device=dev), FlowEstimator()
vids = sorted(vdir.glob("*.mp4"))[:5]
T = {"detect_track": [], "kinematics": [], "scene": [], "flow": [], "lane": []}
for v in vids:
    cap = cv2.VideoCapture(str(v))
    frames = []
    while True:
        ok, f = cap.read()
        if not ok:
            break
        frames.append(f)
    H, W = frames[0].shape[:2]
    kin = TrackKinematics(W, H)
    det.reset(); fe.reset()
    det.track(frames[0]); det.reset()          # warm-up
    for i, f in enumerate(frames[:40]):
        t0 = time.perf_counter(); d = det.track(f); t1 = time.perf_counter()
        kin_d = kin.update(i / 10, d); frame_summary(kin_d, W, H); t2 = time.perf_counter()
        scene_features(f); t3 = time.perf_counter()
        fe.update(f); t4 = time.perf_counter()
        detect_lane(f); t5 = time.perf_counter()
        for k, (a, b) in zip(T, [(t0, t1), (t1, t2), (t2, t3), (t3, t4), (t4, t5)]):
            T[k].append(1000 * (b - a))
res = {k: float(np.median(v)) for k, v in T.items()}
res["total_ms"] = sum(v for k, v in res.items())
res["fps_end_to_end"] = 1000.0 / res["total_ms"]
res["fps_without_lane"] = 1000.0 / (res["total_ms"] - res["lane"])
res["n_frames"] = len(T["flow"])
import torch
res["device"] = torch.cuda.get_device_name(0) if dev != "cpu" and torch.cuda.is_available() else "CPU"
out = Path(C.OUT) / "eval"; out.mkdir(parents=True, exist_ok=True)
(out / "runtime.json").write_text(json.dumps(res, indent=2))
print(json.dumps(res, indent=2))
M = {"RtDetect": f"{res['detect_track']:.0f}", "RtScene": f"{res['scene']:.0f}", "RtFlow": f"{res['flow']:.0f}",
     "RtLane": f"{res['lane']:.0f}", "RtKin": f"{res['kinematics']:.1f}", "RtTotal": f"{res['total_ms']:.0f}",
     "RtFPS": f"{res['fps_end_to_end']:.0f}", "RtFPSNoLane": f"{res['fps_without_lane']:.0f}",
     "RtDevice": res["device"]}
with open(pdir / "generated_runtime.tex", "w") as f:
    f.write("% AUTO-GENERATED by 08_runtime.py\n")
    for k, v in M.items():
        f.write(f"\\def\\{k}{{{v}}}\n")
