"""STEP 9: small descriptive macros for the paper (encoding differences between accident and normal clips,
source-matching feasibility, within-accident split sizes). Reads results/eval/eval_summary.json and the nuisance CSVs.

python 09_extra_macros.py results ../../../paper
"""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

res, paper = Path(sys.argv[1]), Path(sys.argv[2])
c = pd.read_csv(res / "nuisance_crash.csv")
n = pd.read_csv(res / "nuisance_normal.csv")
S = json.loads((res / "eval" / "eval_summary.json").read_text())
M = {}
kb = lambda s: 1e-3 * s.median()
M["BitrateCrash"], M["BitrateNormal"] = f"{kb(c.bytes_per_s):.0f}", f"{kb(n.bytes_per_s):.0f}"
M["BitrateRatio"] = f"{n.bytes_per_s.median() / c.bytes_per_s.median():.1f}"
M["BppCrash"], M["BppNormal"] = f"{c.bits_per_pixel.median():.2f}", f"{n.bits_per_pixel.median():.2f}"
M["NoiseCrash"], M["NoiseNormal"] = f"{c.noise_sigma.median():.1f}", f"{n.noise_sigma.median():.1f}"
M["ResOtherCrash"] = int(((c.width != 1280) | (c.height != 720)).sum())
M["ResOtherNormal"] = int(((n.width != 1280) | (n.height != 720)).sum())
M["FrameDiffCrash"], M["FrameDiffNormal"] = f"{c.framediff_first1s.median():.1f}", f"{n.framediff_first1s.median():.1f}"
M["NFramesOtherNormal"] = int((n.n_frames != 50).sum())
lo = min(c.bytes_per_s.quantile(0.95), n.bytes_per_s.quantile(0.05))
M["BitrateOverlapCrash"] = f"{100 * (c.bytes_per_s > n.bytes_per_s.quantile(0.05)).mean():.0f}"
M["BitrateOverlapNormal"] = f"{100 * (n.bytes_per_s < c.bytes_per_s.quantile(0.95)).mean():.0f}"
ctrl = pd.read_csv(res / "eval" / "control_comparison.csv").set_index("cue")
for cue, nm in [("flow_mag_center", "Flow"), ("has_det", "Det"), ("n_vehicles", "Veh"), ("max_inv_ttc_path", "InvTTC"),
                ("flow_div_center_p90", "DivP")]:
    r = ctrl.loc[cue]
    M[f"Ctrl{nm}Rrb"] = f"{r.r_rb:.2f}"      # used inside math mode in main.tex ($r_{rb}=...$), so a plain minus sign
    M[f"Ctrl{nm}P"] = "$<$0.001" if r.p_holm < 1e-3 else f"{r.p_holm:.3f}"
if "matching" in S:
    m = S["matching"]
    M["MatchPairs"], M["MatchPropAUC"] = m["pairs"], f"{m['propensity_oof_auc']:.3f}"
with open(paper / "generated_extra.tex", "w", newline="\n") as f:
    f.write("% AUTO-GENERATED by 09_extra_macros.py -- do not edit by hand.\n")
    for k, v in M.items():
        f.write("\\def\\" + k + "{" + str(v) + "}\n")
print(M)
